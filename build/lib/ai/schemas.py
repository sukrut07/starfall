"""STARFALL Pydantic Schemas for Model Output Validation."""

from __future__ import annotations

from typing import List, Optional, Literal
from pydantic import BaseModel, Field, field_validator


import typing

FormationType = Literal[
    "v_formation",
    "center_sweep",
    "left_flank",
    "right_flank",
    "split_formation",
    "staggered_assault",
    "converging_pincer",
]

ObstacleType = Literal[
    "none",
    "slow_moving_barriers",
    "telegraphed_laser_lane",
    "drifting_asteroids",
]

ALLOWED_FORMATIONS = list(typing.get_args(FormationType))
ALLOWED_OBSTACLES = list(typing.get_args(ObstacleType))


class TacticalStrategyResponse(BaseModel):
    """Structured strategy plan generated by the AI Tactical Director."""
    formation: FormationType = Field(..., description="Enemy formation name from allowed list")
    obstacle: ObstacleType = Field(default="none", description="Obstacle pattern from allowed list")
    difficulty: int = Field(default=2, ge=1, le=5, description="Wave difficulty tier (1-5)")
    spawn_count: int = Field(default=8, ge=3, le=18, description="Number of enemy ships")
    projectile_speed: float = Field(default=240.0, ge=140.0, le=500.0, description="Enemy projectile speed")
    reason: str = Field(..., description="Concise evidence-based reason for this choice")
    evidence: List[str] = Field(default_factory=list, description="List of observed metrics cited")
    confidence: float = Field(default=0.5, ge=0.0, le=1.0, description="Confidence in adaptation")
    mission: Optional[str] = Field(default=None, description="Optional player mission for this wave")

    @field_validator("formation")
    @classmethod
    def validate_formation(cls, v: str) -> str:
        clean = v.strip().lower()
        if clean not in ALLOWED_FORMATIONS:
            raise ValueError(f"Unknown formation '{v}'. Allowed: {ALLOWED_FORMATIONS}")
        return clean

    @field_validator("obstacle")
    @classmethod
    def validate_obstacle(cls, v: str) -> str:
        clean = v.strip().lower()
        if clean not in ALLOWED_OBSTACLES:
            raise ValueError(f"Unknown obstacle '{v}'. Allowed: {ALLOWED_OBSTACLES}")
        return clean


class PostGameAnalysisResponse(BaseModel):
    """Structured post-game analysis generated by the AI Coach."""
    strengths: List[str] = Field(default_factory=list, description="Tactical strengths observed")
    weaknesses: List[str] = Field(default_factory=list, description="Vulnerabilities or habits observed")
    tactical_adaptation_summary: str = Field(..., description="Summary of how enemies adapted to player")
    next_mission_title: str = Field(..., description="Title of recommended training mission")
    next_mission_objective: str = Field(..., description="Specific measurable training objective")
    supporting_metrics: List[str] = Field(default_factory=list, description="Telemetry metrics cited")
